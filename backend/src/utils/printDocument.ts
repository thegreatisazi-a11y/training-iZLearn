/**
 * Server-side renderer for every printable document in the app.
 *
 * WHY THIS EXISTS
 * Printing used to be done entirely in the browser: each page built its own HTML and called
 * `window.print()` on a blank popup. That had three problems.
 *
 *  1. The browser draws its own header/footer on an HTML print job - the date, the document
 *     title, `about:blank` for the URL, and a page counter - and nothing in CSS can suppress
 *     them. Only the operator's "Headers and footers" checkbox controls them, so a printed
 *     record's appearance depended on a per-machine browser setting.
 *  2. A page number cannot be produced client-side at all: Chrome supports neither CSS page
 *     margin boxes nor `counter(page)` in printed content. The `1/1` on those printouts was
 *     the browser's, not ours.
 *  3. Most importantly, the document was composed from whatever the browser had on screen -
 *     a filtered page of rows, data fetched an hour ago, or (in My CV) an unsaved form - yet
 *     it was stamped "Generated by <user>" as though the system had attested to it. A printed
 *     record is supposed to be an accurate and complete copy of the electronic record
 *     (21 CFR 11.10(b)) with the act of producing it captured in the audit trail (11.10(e));
 *     a copy of a browser view satisfies neither.
 *
 * So documents are now rendered here, from data re-read out of the database under the
 * caller's own permissions, and Puppeteer draws the header/footer we specify and nothing else.
 *
 * The stylesheet below is deliberately a copy of the one the client print helper used, so the
 * documents look the same as before apart from the furniture. Anything that changed layout
 * would be an unrelated change riding along with this one.
 */
import { renderPdfFromHtml } from './pdfGenerator';
import { buildHeaderTemplate, buildFooterTemplate, escapeHtml } from './reportHeader';

export { escapeHtml };

/** Shared print stylesheet. Mirrors the former client-side `printHtml` styles. */
const DOCUMENT_CSS = `
  * { box-sizing: border-box; }
  body { font-family: Inter, system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; color: #1e293b; margin: 0; }
  h1 { font-size: 20px; margin: 0 0 4px; }
  .sub { color: #64748b; font-size: 12px; margin-bottom: 20px; }
  table { width: 100%; border-collapse: collapse; margin: 12px 0; font-size: 13px; }
  th, td { text-align: left; padding: 6px 10px; border-bottom: 1px solid #e2e8f0; vertical-align: top; }
  th { color: #475569; font-weight: 600; background: #f8fafc; }
  .section { font-size: 13px; font-weight: 600; color: #334155; margin: 18px 0 6px; text-transform: uppercase; letter-spacing: .03em; }
  .meta { font-size: 12px; color: #475569; }
  /* Repeat table headers when a long table breaks across pages, and never split a row. */
  thead { display: table-header-group; }
  tr { page-break-inside: avoid; }
`;

/** Build a simple `<table>` from headers + rows. Twin of the client's `printTable`. */
export function printTable(headers: string[], rows: Array<Array<unknown>>): string {
  const head = headers.map((h) => `<th>${escapeHtml(String(h))}</th>`).join('');
  const body = rows
    .map((r) => `<tr>${r.map((c) => `<td>${escapeHtml(cellText(c))}</td>`).join('')}</tr>`)
    .join('');
  return `<table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>`;
}

/** Empty cells print as an em dash so a blank column is visibly blank, not ambiguous. */
function cellText(value: unknown): string {
  if (value === null || value === undefined || value === '') return '—';
  return String(value);
}

export interface DocumentRenderContext {
  title: string;
  bodyHtml: string;
  orgName: string;
  orgLogoPath?: string;
  generatedByName: string;
  generatedByEmployeeId: string;
  timezone?: string;
  landscape?: boolean;
}

/** Render a document body to a PDF Buffer with the standard header and footer. */
export async function renderDocumentPdf(ctx: DocumentRenderContext): Promise<Buffer> {
  const cfg = {
    orgName: ctx.orgName,
    // A relative logo path cannot resolve inside Puppeteer's own document, so it is dropped
    // rather than rendered as a broken image. Same guard the report PDFs already use.
    orgLogoPath: ctx.orgLogoPath && /^(https?:|data:)/.test(ctx.orgLogoPath) ? ctx.orgLogoPath : undefined,
    reportTitle: ctx.title,
    generatedByName: ctx.generatedByName,
    generatedByEmployeeId: ctx.generatedByEmployeeId,
    generatedAt: new Date(),
    timezone: ctx.timezone,
  };

  const html = `<!doctype html>
<html>
<head><meta charset="utf-8" /><title>${escapeHtml(ctx.title)}</title>
<style>${DOCUMENT_CSS}</style>
</head>
<body>${ctx.bodyHtml}</body>
</html>`;

  return renderPdfFromHtml(html, {
    headerHtml: buildHeaderTemplate(cfg),
    footerHtml: buildFooterTemplate(cfg),
    landscape: ctx.landscape,
  });
}
