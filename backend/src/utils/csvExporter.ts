export interface CsvColumn {
  header: string;
  key: string;
}

export function escapeCsv(value: unknown): string {
  let s = value === null || value === undefined ? '' : String(value);
  // CSV formula-injection defence: a cell whose first character is = + - @ (or a
  // leading tab/CR) is evaluated as a formula by Excel/LibreOffice. Prefix such values
  // with an apostrophe so they are rendered as literal text, never executed.
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/**
 * Render columns + rows to a CSV string (RFC-4180 quoting).
 *
 * NO footer, deliberately. CSV is an interchange format, not a document: the old trailing
 * "Generated by ..." line (after a blank row) made the file invalid as data - Excel pivots,
 * pandas and any downstream import read it as a junk row. Attribution lives in the
 * standardised filename (exportFilename) and in the AuditTrail EXPORT event, which records
 * the actor, timestamp and row count. Excel and PDF keep their document furniture.
 *
 * `meta` is accepted and ignored so the existing call sites need no change.
 */
export function exportToCsv(
  columns: CsvColumn[],
  rows: Array<Record<string, unknown>>,
  _meta?: { generatedBy?: string; timezone?: string },
): string {
  const head = columns.map((c) => escapeCsv(c.header)).join(',');
  const body = rows.map((r) => columns.map((c) => escapeCsv(r[c.key])).join(',')).join('\r\n');
  return `${head}\r\n${body}`;
}
