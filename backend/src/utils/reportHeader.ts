import { formatDateTime, APP_TIMEZONE } from './dateUtils';

export interface ReportHeaderConfig {
  orgName: string;
  orgLogoPath?: string;
  reportTitle: string;
  generatedByName: string;
  generatedByEmployeeId: string;
  generatedAt: Date;
  timezone?: string;
}

/*
 * NOTE: there is deliberately no reference number. It used to print "Ref: REP-<ts>-<rand>"
 * in the header, minted fresh on every render and stored nowhere - two prints of the same
 * record produced different references and neither could be looked up. A traceability
 * identifier nobody can resolve is worse than none, because it implies a lookup exists.
 * The record's own identifiers (course code, JD/CV version, certificate number) are the
 * real handles, and the AuditTrail PRINT event is the record of the act of printing.
 *
 * NOTE: there is deliberately no "Printed By". Generating and printing are the same HTTP
 * request by the same authenticated user, so it always repeated the Generated By name and
 * implied two recorded events where only one happened. The authoritative record of who
 * exported or printed what is the AuditTrail EXPORT / PRINT event.
 */

/**
 * Puppeteer header/footer templates. Puppeteer substitutes the special classes
 * `pageNumber` and `totalPages` at print time so every page shows "Page X of Y".
 * Used by every report and printed document (Module 11).
 */
export function buildHeaderTemplate(cfg: ReportHeaderConfig): string {
  const logo = cfg.orgLogoPath
    ? `<img src="${cfg.orgLogoPath}" style="height:28px;margin-right:10px;" />`
    : '';
  return `
  <div style="font-size:9px;width:100%;padding:4px 12px;border-bottom:1px solid #ccc;display:flex;align-items:center;justify-content:space-between;">
    <div style="display:flex;align-items:center;">${logo}<strong>${escapeHtml(cfg.orgName)}</strong></div>
    <div style="text-align:right;"><strong>${escapeHtml(cfg.reportTitle)}</strong></div>
  </div>`;
}

export function buildFooterTemplate(cfg: ReportHeaderConfig): string {
  const tz = cfg.timezone || APP_TIMEZONE;
  const generated = formatDateTime(cfg.generatedAt, tz);

  return `
  <div style="font-size:8px;width:100%;padding:4px 12px;border-top:1px solid #ccc;display:flex;justify-content:space-between;">
    <div>Generated by ${escapeHtml(cfg.generatedByName)} (${escapeHtml(cfg.generatedByEmployeeId)}) on ${generated}</div>
    <div>Page <span class="pageNumber"></span> of <span class="totalPages"></span></div>
  </div>`;
}

export function escapeHtml(s: string): string {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
