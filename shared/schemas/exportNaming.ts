/**
 * Export/print naming + document-furniture helpers, shared by the frontend and backend.
 *
 * These live in `shared` on purpose: exports are produced on BOTH sides (the server builds
 * reports, the audit trail and the master CSVs; the browser builds the per-module print
 * views and table CSVs). Defining the filename and reference formats once is the only way
 * they stay identical.
 *
 * No dependencies — `shared` carries only zod, so the IST formatting is done with Intl.
 */

/** The application's display timezone. Every user-visible date/time renders in IST. */
export const APP_TIMEZONE = 'Asia/Kolkata';

/** The calendar/clock parts of an instant as seen in IST, regardless of host timezone. */
function istParts(date: Date): Record<string, string> {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: APP_TIMEZONE,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
  }).formatToParts(date);
  const out: Record<string, string> = {};
  for (const p of parts) if (p.type !== 'literal') out[p.type] = p.value;
  // 'en-GB' can render midnight as hour 24; normalise so a filename never says 24xx.
  if (out.hour === '24') out.hour = '00';
  return out;
}

/** `YYYYMMDD-HHmm` in IST — the timestamp component of every export filename. */
export function exportStamp(date: Date = new Date()): string {
  const p = istParts(date);
  return `${p.year}${p.month}${p.day}-${p.hour}${p.minute}`;
}

/** Lower-case, hyphenated, filesystem-safe slug (for a role/course name in a filename). */
export function slugify(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/[\s_]+/g, '-')
    .replace(/-+/g, '-')
    .toLowerCase()
    .slice(0, 60);
}

/**
 * The ONE filename format for every export and download:
 *
 *     izlearn_<subject>_<YYYYMMDD-HHmm>.<ext>
 *     izlearn_courses_20260908-1425.csv
 *     izlearn_role-permissions-super-admin_20260908-1425.csv
 *
 * Sorts chronologically, never collides across modules, and says what it is without being
 * opened. The timestamp is IST so it matches the "Generated by … on …" line inside.
 */
export function exportFilename(subject: string, ext: string, date: Date = new Date()): string {
  const safeExt = ext.replace(/^\./, '').toLowerCase();
  return `izlearn_${slugify(subject)}_${exportStamp(date)}.${safeExt}`;
}
